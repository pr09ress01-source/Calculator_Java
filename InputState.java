//電卓の現在の入力状態を表す列挙型（enum）
//CalculatorModelが、ユーザーの操作をどう解釈するかの判断基準になる
public enum InputState {

	//何も入力していない状態、または計算が終わった直後の初期状態
    //例：アプリ起動直後、Cでクリアした直後、=の結果を表示している直後
    READY,

    //ユーザーが「数字を入力中」の状態
    //例：1→12→123と、0〜9または.を押している最中
    INPUT_NUMBER,

    //ユーザーが「演算子を入力した直後」の状態
    //例：1 + まで入力した状態。次は数字を入力する
    INPUT_OPERATOR,

    //エラーが発生している状態
    //この状態では、次の数字入力で初期化
    ERROR
}